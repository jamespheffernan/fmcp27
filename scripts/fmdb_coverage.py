"""Coverage run: every editor record type x every editor field through the PropertyVM.

Usage: PYTHONPATH=. python scripts/fmdb_coverage.py [--per-type 25] [--types play,club]
           [--budget 500000] [--out out/fmdb-coverage] [--plans]

Writes <out>/coverage.json (untracked). Per record type and field it records how many
sampled records returned a value, an unset/empty value, a null the getter did not
claim (w0 == 0: 'not_handled'), or Unavailable (by reason),
plus call timing, instruction counts, modelled externals and refused externals.
With --plans it also traces loads (fmdb.plans) and writes <out>/plans.json.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import statistics
import struct
import sys
import time

from fm_live_mcp.fmdb import tables, variant
from fm_live_mcp.fmdb._editor_fields import editor_path, load_fields
from fm_live_mcp.fmdb.image import PluginImage
from fm_live_mcp.fmdb.live import open_live
from fm_live_mcp.fmdb.vm import PropertyVM, Unavailable


def outcome(result):
    value = result.value
    if isinstance(value, Unavailable):
        return 'unavailable', value.reason
    if result.kind == 'null' and result.handled is False:
        return 'not_handled', None
    if result.kind == 'null' or value is None or value == '' or value == [] or value == {}:
        return 'unset', None
    if isinstance(value, dict) and any(isinstance(v, Unavailable) for v in value.values()):
        return 'unavailable', 'record entry unavailable'
    if isinstance(value, list) and any(isinstance(v, Unavailable) for v in value):
        return 'unavailable', 'list element unavailable'
    return 'value', None


def infer_ref_tables(read, base, examples):
    """Map each reference FourCC to the one table whose records carry all example ids."""
    candidates = [k for k in tables.database.TABLES if k != 'removed_records']
    found = {}
    for fourcc, refs in examples.items():
        if fourcc in tables.REF_TABLES:
            found[fourcc] = {'table': tables.REF_TABLES[fourcc], 'how': 'declared'}
            continue
        hits = []
        for kind in candidates:
            index = tables.unique_id_index(read, base, kind)
            ok = True
            for ref in refs:
                hit = index.get(ref.unique_id)
                if hit is None:
                    ok = False
                    break
                rid = struct.unpack('<I', read(hit[1] + 0x10, 4))[0]
                if (rid or ref.unique_id) != ref.random_id:
                    ok = False
                    break
            if ok:
                hits.append(kind)
        found[fourcc] = {'table': hits[0] if len(hits) == 1 else None, 'candidates': hits,
                         'how': f'unique+random id match on {len(refs)} examples'}
    return found


def render(report):
    t = report['timing']
    rows = report['record_types']
    total = sum(r['fields'] for r in rows.values())
    agg = Counter()
    for r in rows.values():
        agg.update(r['field_status'])
    lines = [
        '# fmdb PropertyVM coverage',
        '',
        f"Generated by `scripts/fmdb_coverage.py` (per type {report['settings']['per_type']} sampled records "
        f"plus the managed club / squad where relevant; view `{report['settings']['view']}`, thread "
        f"`{report['settings']['thread']}`, budget {report['settings']['budget']:,} instructions). "
        'A field counts as **value** when at least one sampled record returned a decoded, non-empty '
        'value; **unset** when the getter claimed it but every record was null/empty; **not handled** '
        'when the getter returned 0 with a null value for every record; otherwise **unavailable**, '
        'grouped by the most common reason.',
        '',
        f"Totals: {len(rows)} record types, {total} (type, field) pairs: "
        + ', '.join(f'{k} {v}' for k, v in agg.most_common()) + '.',
        '',
        f"Calls: {t['calls']:,}; mean {t['mean_ms']} ms, median {t['median_ms']} ms, p95 {t['p95_ms']} ms per call; "
        f"instructions mean {t['mean_instructions']:,}, median {t['median_instructions']:,}, max {t['max_instructions']:,}. "
        f"Wall time {t['wall_seconds']} s; {t['live_pages_cached']:,} live pages and {t['code_pages']} code pages cached; "
        f"{t['reader_reads']:,} reader calls ({t['reader_bytes'] / 1e6:.1f} MB).",
        '',
        '| type | table | records | fields | value | unset | not handled | unavailable | unavailable by reason | mean ms |',
        '|---|---|---|---|---|---|---|---|---|---|',
    ]
    for rtype, r in rows.items():
        st = r['field_status']
        reasons = '; '.join(f'{k} ({v})' for k, v in sorted(r['unavailable_fields_by_reason'].items(),
                                                              key=lambda kv: -kv[1]))
        lines.append(f"| {rtype} | {r['table']} | {r['records']} | {r['fields']} | {st.get('value', 0)} | "
                     f"{st.get('unset', 0)} | {st.get('not_handled', 0)} | {st.get('unavailable', 0)} | "
                     f"{reasons or '-'} | {r['mean_ms']} |")
    lines += ['', '### Per call', '',
              'Every (record, field) call, so a field can count in several columns. Top reasons for '
              'unavailable calls:', '',
              '| type | calls | value | unset | not handled | unavailable | top unavailable reasons (calls) |',
              '|---|---|---|---|---|---|---|']
    all_reasons = Counter()
    for rtype, r in rows.items():
        calls, reasons = Counter(), Counter()
        for row in r['per_field'].values():
            calls.update(row['counts'])
            reasons.update(row['unavailable_reasons'])
        all_reasons.update(reasons)
        top = '; '.join(f'{k} ({v})' for k, v in reasons.most_common(4))
        lines.append(f"| {rtype} | {sum(calls.values())} | {calls.get('value', 0)} | {calls.get('unset', 0)} | "
                     f"{calls.get('not_handled', 0)} | {calls.get('unavailable', 0)} | {top or '-'} |")
    lines += ['', 'All unavailable calls by reason: '
              + '; '.join(f'{k} {v:,}' for k, v in all_reasons.most_common()) + '.']
    lines += ['', 'Record types with no live table: '
              + '; '.join(f'`{k}` ({v})' for k, v in report['no_table'].items()) + '.', '',
              '## External functions', '',
              'Modelled (calls across the run): '
              + ', '.join(f'`{k}` {v:,}' for k, v in report['externals_modelled'].items()) + '.', '',
              'Refused (each stops the call with Unavailable): '
              + (', '.join(f'`{k}` {v:,}' for k, v in report['externals_refused'].items()) or 'none') + '.', '',
              '## Record reference tables', '',
              'Table FourCCs seen in record references and the live table whose records carry the '
              'referenced unique/random ids:', '']
    for fourcc, row in sorted(report['reference_tables'].items()):
        lines.append(f"- `{fourcc}` -> {row.get('table') or 'unresolved'}"
                     + (f" (candidates {row.get('candidates')})" if not row.get('table') else '')
                     + f" ({row['how']})")
    return '\n'.join(lines) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--per-type', type=int, default=25)
    ap.add_argument('--types')
    ap.add_argument('--budget', type=int, default=500_000)
    ap.add_argument('--out', default='out/fmdb-coverage')
    ap.add_argument('--plans', action='store_true')
    ap.add_argument('--markdown', help='also render a summary to this Markdown path')
    ap.add_argument('--render', help='only render an existing coverage.json to --markdown')
    args = ap.parse_args(argv)
    if args.render:
        Path(args.markdown).write_text(render(json.loads(Path(args.render).read_text())))
        return 0
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    session = open_live()
    started = time.time()
    try:
        read, base = session.reader.read, session.base
        image = PluginImage.load(session.plugin_path)
        vm = PropertyVM(session.reader, base, image, budget=args.budget,
                        file_resolver=session.file_resolver())
        tracer = None
        if args.plans:
            from fm_live_mcp.fmdb import plans
            tracer = plans.Tracer(vm)
        fields = load_fields(str(editor_path(session.plugin_path)))
        managed_clubs, managed_people = tables.managed(read, base)
        wanted = args.types.split(',') if args.types else list(tables.RECORD_TYPES)
        pointer_cache, class_cache = {}, {}
        report = {'build': {'plugin': str(session.plugin_path), 'base': hex(base)},
                  'settings': {'per_type': args.per_type, 'budget': args.budget, 'view': vm.view,
                               'thread': vm.thread},
                  'record_types': {}, 'no_table': tables.NO_TABLE}
        times, instructions = [], []
        ref_examples = defaultdict(list)
        for rtype in wanted:
            spec = tables.RECORD_TYPES[rtype]
            if spec.table not in pointer_cache:
                pointer_cache[spec.table] = tables.entries(read, base, spec.table)
            if spec.classes and spec.table not in class_cache:
                class_cache[spec.table] = tables.classify(read, base, pointer_cache[spec.table])
            records = tables.sample(read, base, rtype, args.per_type, pointers=pointer_cache[spec.table],
                                    classes=class_cache.get(spec.table))
            extra = []
            if rtype in ('club', 'c2tm', 'c3tm', 'c4tm'):
                extra = managed_clubs
            elif rtype in ('play', 'pers', 'CntF'):
                extra = managed_people
            records = list(dict.fromkeys(records + extra))
            classes = Counter(tables.class_of(read, base, r)[0] for r in records)
            per_field = {}
            type_times = []
            for field in fields.get(rtype, []):
                counts = Counter()
                reasons = Counter()
                kinds = Counter()
                example = None
                for record in records:
                    result = (tracer.get_property(record, field.code) if tracer
                              else vm.get_property(record, field.code))
                    status, reason = outcome(result)
                    counts[status] += 1
                    if reason:
                        reasons[reason] += 1
                    if result.kind:
                        kinds[result.kind] += 1
                    if status == 'value' and example is None:
                        example = variant.to_json(result.value)
                    if isinstance(result.value, variant.RecordRef) and len(ref_examples[result.value.table]) < 5:
                        ref_examples[result.value.table].append(result.value)
                    times.append(result.stats.seconds)
                    type_times.append(result.stats.seconds)
                    instructions.append(result.stats.instructions)
                per_field[field.code] = {
                    'name': field.name, 'editor_type': field.type, 'counts': dict(counts),
                    'unavailable_reasons': dict(reasons), 'kinds': dict(kinds),
                    'example': example if not isinstance(example, (bytes, bytearray)) else None}
            status = Counter()
            reasons = Counter()
            for row in per_field.values():
                c = row['counts']
                if c.get('value'):
                    status['value'] += 1
                elif c.get('unset'):
                    status['unset'] += 1
                elif c.get('not_handled'):
                    status['not_handled'] += 1
                else:
                    status['unavailable'] += 1
                    top = max(row['unavailable_reasons'].items(), key=lambda kv: kv[1])[0] \
                        if row['unavailable_reasons'] else 'no records'
                    reasons[top] += 1
            report['record_types'][rtype] = {
                'table': spec.table, 'note': spec.note, 'records': len(records),
                'classes': dict(classes), 'fields': len(per_field), 'field_status': dict(status),
                'unavailable_fields_by_reason': dict(reasons),
                'mean_ms': round(1000 * statistics.fmean(type_times), 3) if type_times else None,
                'per_field': per_field}
            print(f'{rtype:5} {spec.table:24} records={len(records):3} fields={len(per_field):3} '
                  f'{dict(status)} {time.time() - started:.0f}s', flush=True)
        report['reference_tables'] = {k: v for k, v in infer_ref_tables(read, base, ref_examples).items()}
        report['timing'] = {
            'calls': len(times),
            'mean_ms': round(1000 * statistics.fmean(times), 3),
            'median_ms': round(1000 * statistics.median(times), 3),
            'p95_ms': round(1000 * sorted(times)[int(len(times) * 0.95)], 3),
            'mean_instructions': round(statistics.fmean(instructions), 1),
            'median_instructions': statistics.median(instructions),
            'max_instructions': max(instructions),
            'live_pages_cached': len(vm.live_pages), 'code_pages': len(vm.code_pages),
            'reader_reads': session.reader.total_reads, 'reader_bytes': session.reader.total_bytes,
            'wall_seconds': round(time.time() - started, 1)}
        report['externals_modelled'] = dict(vm.stubbed.most_common())
        report['externals_refused'] = dict(vm.refused.most_common())
        (out_dir / 'coverage.json').write_text(json.dumps(report, indent=1, default=str))
        if tracer:
            tracer.write(out_dir / 'plans.json')
        print(json.dumps(report['timing']), flush=True)
        if args.markdown:
            Path(args.markdown).write_text(render(report))
        return 0
    finally:
        session.close()


if __name__ == '__main__':
    sys.exit(main())
