"""Current COMP-owned resident individual goals; no native sorting or refresh."""
import struct

from . import assessment_people, competition_stages, database, players, world
from .league_scorers import MAX_CANDIDATES

STATS_TYPE = (0x55DCCB8, b'15GAME_COMP_STATS')
SUPPORTED_COMPETITION_TYPES = (0, 1, 14)
ACTUAL_COMP = 0x566C2B8


class UnsupportedPool(ValueError):
    """An ambiguous resident representation must not become a partial full rank."""


def verify_native(read, base):
    for rva, raw in NATIVE_SPANS:
        if read(base + rva, len(raw)) != raw:
            raise ValueError(f'Competition goals native source changed at RVA {rva:#x}')


def _pointer(value, alignment=8):
    if value < 4096 or value % alignment or value + 16 >= 1 << 64:
        raise ValueError('Invalid competition scorer source pointer')
    return value


def _unavailable(context, reason):
    return {
        **context,
        'source_state': 'unavailable',
        'unavailable_reason': reason,
        'complete_resident_pool': False,
        'physical_count': None,
        'stored_goals_sum': None,
        'unknown_identity_count': None,
    }, []


def collect(read, base, saved):
    """Return public coverage and private scalar candidates from every physical row."""
    verify_native(read, base)
    context, runtime, binding = competition_stages.runtime_context(read, base, saved)
    kind = context['competition']['context']['competition_type']['native_code']
    if kind not in SUPPORTED_COMPETITION_TYPES:
        return _unavailable(context, 'unsupported_competition_kind_for_league_query')
    if runtime is None:
        return _unavailable(context, 'current_runtime_competition_absent')
    if binding[1] != ACTUAL_COMP:
        return _unavailable(context, 'unsupported_runtime_competition_type')
    if context['shared_runtime']:
        return _unavailable(context, 'shared_runtime_competition_owner')
    if context['native_season_code'] == 0:
        return _unavailable(context, 'native_season_not_materialized')
    stats = players.u64(read(runtime + 0x390, 8))
    if not stats:
        return _unavailable(context, 'current_competition_stats_not_resident')
    _pointer(stats)
    competition_stages.typed(read, base, stats, STATS_TYPE)
    if (players.u64(read(base + STATS_TYPE[0] + 0x40, 8)) != base + 0xF3CA9C
            or world.pointer(read, stats + 0x7B8) != binding[2]):
        raise ValueError('Competition scorer stats type or COMP ownership changed')
    start, end, capacity = struct.unpack('<QQQ', read(stats + 0x1278, 24))
    if (start, end, capacity) == (0, 0, 0):
        pointers = ()
    else:
        _pointer(start)
        if (not start <= end <= capacity or end % 8 or capacity % 8
                or capacity - start > MAX_CANDIDATES * 8):
            return _unavailable(context, 'resident_pool_geometry_or_reader_budget_unsupported')
        pointers = tuple(value for cursor in range(start, end, 16384)
                         for (value,) in struct.iter_unpack('<Q', read(cursor, min(16384, end-cursor))))
    people = database.table(read, base, 'people')
    assessment_people.verify_native(read, base)
    candidates = []
    seen = set()
    unknown = 0
    unsupported_profiles = 0
    for ordinal, pointer in enumerate(pointers):
        # PERSON_COMP_STATS allocator stride is 0xAC: rows need four-byte alignment.
        _pointer(pointer, alignment=4)
        raw = read(pointer, 16)
        index, team_index = struct.unpack_from('<II', raw)
        if index in seen:
            return _unavailable(context, 'ambiguous_duplicate_person_entries')
        seen.add(index)
        if index >= 2**31:
            return _unavailable(context, 'unsupported_stored_person_index')
        candidate = {
            'source_ordinal': ordinal,
            'person_index': index,
            'goals': raw[0xC],
            'last_associated_team_index': None if team_index == 0xFFFFFFFF else team_index,
            'identity_state': 'unresolved_canonical_person',
            '_primary_address': None,
            '_identity': None,
        }
        person = players.u64(read(people['start'] + index * 8, 8)) if index < people['count'] else 0
        if person:
            _pointer(person)
            vtable, original, native, secondary = struct.unpack('<QIII', read(person, 20))
            _pointer(vtable)
            if original != index or not native:
                raise ValueError('Competition scorer PERSON identity changed')
            if vtable - base not in assessment_people._PERSON_TYPES:
                unsupported_profiles += 1
                candidate['identity_state'] = 'unsupported_person_profile'
            else:
                primary, _, identity, _, _ = assessment_people._person(read, base, people, person)
                candidate.update(_primary_address=primary, _identity=identity,
                                 identity_state='canonical_person')
                if identity['record_kind'] not in ('actual', 'player_staff'):
                    unsupported_profiles += 1
                    candidate['identity_state'] = 'unsupported_person_profile'
        else:
            unknown += 1
        candidates.append(candidate)
    return {
        **context,
        'source_state': 'available',
        'unavailable_reason': None,
        'complete_resident_pool': True,
        'physical_count': len(candidates),
        'stored_goals_sum': sum(row['goals'] for row in candidates),
        'unknown_identity_count': unknown,
        'unsupported_player_profile_count': unsupported_profiles,
        'source_population': 'every physical entry in current COMP-owned resident PERSON stats vector',
        'goal_encoding': 'unsigned8 cumulative stored competition PERSON counter; 255 is a value',
        'native_sort_executed': False,
        'native_refresh_executed': False,
        'native_row_creation_executed': False,
        'last_team_scope': 'last associated TEAM; individual goals can accumulate across transfers',
    }, candidates


