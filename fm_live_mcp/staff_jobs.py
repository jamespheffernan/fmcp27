def decode(read, base, contract, table, team):
    from .players import u64

    if u64(read(table + 11 * 8, 8)) != base + 0xD8C3C8:
        raise ValueError('Contract job getter changed')
    native_code = read(contract + 0x26, 1)[0]
    team_type = read(team + 0x28, 1)[0]
    # The native converter returns zero for unsupported team/job combinations.
    # Preserve that distinction instead of calling an employed person jobless.
    group = TEAM_GROUP[team_type] if team_type < len(TEAM_GROUP) else 2
    code = JOB_GROUPS[group][native_code] if native_code < 90 else 0
    return {'title': JOB_LABELS[code] if code else None,
            'state': 'decoded' if code else 'unmapped_native_job',
            'native_code': native_code, 'team_type_code': team_type,
            'evidence': 'native_contract_job_and_team_conversion_with_installed_labels'}
