SCOPE = ('Stored language name, nation, family/group/subgroup, influence and difficulty. '
         'Classification labels come from the installed editor; unknown codes remain unmapped. '
         'DELE is the native family == -1 predicate. Ratings are stored values, not a prediction of learning time, '
         'player fluency, recruitment suitability or national prevalence. Names omit contextual formatting. '
         'References bind to native identity and canonical membership; ordinary fields refresh. '
         'Non-atomic reads with consumed-byte rechecks. Follow every cursor, including empty pages.')


def classification(code, labels):
    return {'native_code':code,'name':labels.get(code),'state':'decoded' if code in labels else 'unmapped'}


def record(read, base, address, *, include_details=False):
    binding = geography.identity(read,base,address,'language')
    row = {**geography.record(read,base,address,'language'),'kind':'language'}
    family = int.from_bytes(read(address+0x34,2),'little',signed=True)
    row['is_deleted'] = family == -1
    if include_details:
        nation = players.u64(read(address+0x28,8))
        row.update(nation=geography.record(read,base,nation,'nation') if nation else None,
            family=classification(family,FAMILIES),
            group=classification(int.from_bytes(read(address+0x36,2),'little',signed=True),GROUPS),
            subgroup=classification(int.from_bytes(read(address+0x38,2),'little',signed=True),SUBGROUPS),
            influence=int.from_bytes(read(address+0x3B,1),'little',signed=True),
            difficulty=int.from_bytes(read(address+0x3C,1),'little',signed=True))
    return row,binding
