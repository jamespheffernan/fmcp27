"""Live state collections: transfer offers, current injuries, news items.

* transfer_offer: BASE_TRANSFER_MANAGER (global 0x56A49F8) offer vectors +0x20 / +0x38, read with
  the hand-built `live_transfer_offers` manager and vector checks unchanged; each object's class
  by vtable (8 offer classes), person +0x38, teams +0x40/+0x48/+0x50, state byte +0x8D, signed
  amount +0x58 (loans: monthly fee while playing), loan leaf terms +0x100.
* player_injury: every current injury of every player, the player's injury vector (primary
  +0xF0) whose entries point at the typed INJURY definition (+8) and store the start date
  (+0x20), as `player_health.injury` reads it; the vector is the one primary slot 21
  (0xD09BB0) tests, which is checked per class.
* news_item: every item of NEWS_MANAGER (global 0x56A5908) +0xB8 (sorted by unique id): unique
  id +0x90, flags +0x98 (bit 0 read), packed date +0x88, news class from the item's RTTI, and
  whether the human manager's inbox (HUMAN +0x350) holds it. Subject and body are generated by
  UI code and stay with the inbox tool (fm_ui_inbox).
"""
from __future__ import annotations

from collections import Counter
import struct

from ... import live_transfer_offers as offers, player_health, players
from .. import tables as T
from . import Column, SourceTable
from . import _common as C

NEWS_MANAGER = 0x56A5908
HUMAN_INBOX = 0x350


# --------------------------------------------------------------------------- offers
def _offers(engine):
    read, base = engine.read, engine.base
    manager = offers._manager(read, base)
    if manager is None:
        return []
    vectors = offers._vectors(read, manager)
    people = C.index_of(engine, 'people')
    teams = C.index_of(engine, 'teams')
    team_club = C.team_clubs(engine)
    kinds = {base + rva: name for rva, (name, *_rest) in offers.CLASSES.items()}
    rows = []
    addresses = sorted({a for _, _, values in vectors for a in values if a})
    heads = dict(zip(addresses, C.blobs(engine, [(a, 0x110) for a in addresses])))
    for container, _, values in vectors:
        for slot, a in enumerate(values):
            raw = heads.get(a) if a else None
            if not raw:
                continue
            vt = struct.unpack_from('<Q', raw, 0)[0]
            kind = kinds.get(vt)
            if kind is None:
                raise ValueError(f'unknown offer class at vtable {vt - base:#x}')
            person = struct.unpack_from('<Q', raw, 0x38)[0]
            t = struct.unpack_from('<3Q', raw, 0x40)
            amount = struct.unpack_from('<i', raw, 0x58)[0]
            loan = struct.unpack_from('<iii', raw, 0x100) if kind == 'loan' else (None, None, None)
            dates = [C.packed_date(v) for v in struct.unpack_from('<4I', raw, 0x70)]
            rows.append((container, slot, f'{a:#x}', kind, people.get(person) if person else None,
                         teams.get(t[0]), team_club.get(t[0]), teams.get(t[1]), team_club.get(t[1]),
                         teams.get(t[2]), team_club.get(t[2]), raw[0x8D], amount, *dates,
                         loan[2], loan[0], loan[1]))
    return rows


# --------------------------------------------------------------------------- injuries
def _injuries(engine):
    read, base = engine.read, engine.base
    people = C.live(engine, 'people')
    injuries = C.index_of(engine, 'injuries')
    rows, unsupported = [], Counter()
    by_class = {}
    for i, (p, cls) in enumerate(zip(people.pointers, people.classes)):
        if p and cls in ('ACTUAL_PLAYER', 'ACTUAL_PLAYER_AND_NON_PLAYER'):
            by_class.setdefault(cls, []).append(i)
    offsets = {name: off for _, (name, _, off) in T.CLASSES.items() if off is not None}
    for cls, idxs in by_class.items():
        primaries = [people.pointers[i] - offsets[cls] for i in idxs]
        vtable = C.u64s(engine, [primaries[0]])[0]
        if C.u64s(engine, [vtable + 21 * 8])[0] != base + 0xD09BB0:
            unsupported[cls] += len(idxs)
            continue
        headers = C.u64s(engine, [p + 0xF0 for p in primaries])
        vec_reqs = [(h, 24) if h else (0, 0) for h in headers]
        for i, h, raw in zip(idxs, headers, C.blobs(engine, vec_reqs)):
            if not h or not raw:
                continue
            start, end, cap = struct.unpack('<QQQ', raw)
            if start == end:
                continue
            if start % 8 or not start <= end <= cap or end - start > 128 * 8:
                unsupported['invalid vector'] += 1
                continue
            entries = struct.unpack(f'<{(end - start) // 8}Q', read(start, end - start))
            for n, (e, eraw) in enumerate(zip(entries, C.blobs(engine, [(e, 0x38) for e in entries]))):
                if not eraw:
                    continue
                definition = struct.unpack_from('<Q', eraw, 8)[0]
                started = C.packed_date(struct.unpack_from('<I', eraw, 0x20)[0])
                rows.append((i, n, injuries.get(definition), started, f'{e:#x}'))
    C.cache(engine)['injury_unsupported'] = dict(unsupported)
    return rows


# --------------------------------------------------------------------------- news
def _rtti_name(engine, vtable) -> str:
    """Itanium RTTI class name of a vtable (vtable[-1] -> type_info, +8 -> mangled name), digits of
    the length prefix stripped; '' when unreadable. Plain reads, no VM."""
    info = C.u64s(engine, [vtable - 8])[0]
    name = C.u64s(engine, [info + 8])[0] if info else 0
    raw = C.blobs(engine, [(name, 128)])[0] if name else None
    if not raw:
        return ''
    text = raw.split(b'\0', 1)[0].decode('ascii', 'replace')
    return text.lstrip('0123456789')


def _news(engine):
    base = engine.base
    mgr = C.u64s(engine, [base + NEWS_MANAGER])[0]
    if not mgr:
        return []
    start, end = C.u64s(engine, [mgr + 0xB8, mgr + 0xC0])
    if start % 8 or not start <= end or end - start > 1_000_000 * 8:
        raise ValueError('invalid news vector')
    items = C.u64s(engine, [start + 8 * i for i in range((end - start) // 8)])
    from .. import ui_recipes_news as rn
    inbox = []                      # (person idx of the human, item pointer)
    people = C.live(engine, 'people')
    for i, (p, cls) in enumerate(zip(people.pointers, people.classes)):
        if cls == 'HUMAN_NON_PLAYER' and p:
            header = C.u64s(engine, [p - rn.PERSON_HUMAN_OFFSET + HUMAN_INBOX])[0]
            if not header:
                continue
            s, e = C.u64s(engine, [header, header + 8])
            if s and s <= e and e - s <= 100_000 * 8 and not s % 8:
                inbox += [(i, q) for q in C.u64s(engine, [s + 8 * k for k in range((e - s) // 8)]) if q]
    names = {}

    def decode(pointers):
        out = []
        for p, raw in zip(pointers, C.blobs(engine, [(p, 0xA0) for p in pointers])):
            if not raw:
                out.append(None)
                continue
            vt = struct.unpack_from('<Q', raw, 0)[0]
            if vt not in names:
                names[vt] = _rtti_name(engine, vt)
            out.append((struct.unpack_from('<I', raw, 0x90)[0], names[vt],
                        C.packed_date(struct.unpack_from('<I', raw, 0x88)[0]), struct.unpack_from('<H', raw, 0x98)[0]))
        return out

    inbox_rows = decode([q for _, q in inbox])
    in_inbox = {r[0] for r in inbox_rows if r}
    rows = [(unid, cls, d, 'news_manager', None, flags & 1, flags, int(unid in in_inbox))
            for unid, cls, d, flags in filter(None, decode(items))]
    rows += [(r[0], r[1], r[2], 'inbox', owner, r[3] & 1, r[3], 1)
             for (owner, _), r in zip(inbox, inbox_rows) if r]
    return rows


# --------------------------------------------------------------------------- fingerprints
def _offer_fingerprint(engine):
    """Both offer vectors and every offer's 0x110 head (state byte, teams, amount, dates)."""
    from . import digest
    read, base = engine.read, engine.base
    manager = offers._manager(read, base)
    if manager is None:
        return 'none'
    vectors = offers._vectors(read, manager)
    addresses = sorted({a for _, _, values in vectors for a in values if a})
    return digest(*(a for _, _, values in vectors for a in values), *C.blobs(engine, [(a, 0x110) for a in addresses]))


def _injury_fingerprint(engine):
    """Every player's injury vector pointer and bounds: an injury added or healed changes them."""
    from . import digest
    people = C.live(engine, 'people')
    offsets = {name: off for _, (name, _, off) in T.CLASSES.items() if off is not None}
    primaries = [p - offsets[c] for p, c in zip(people.pointers, people.classes)
                 if p and c in ('ACTUAL_PLAYER', 'ACTUAL_PLAYER_AND_NON_PLAYER')]
    headers = C.u64s(engine, [p + 0xF0 for p in primaries])
    return digest(*headers, *C.blobs(engine, [(h, 16) if h else (0, 0) for h in headers]))


def _news_fingerprint(engine):
    """The decoded rows themselves (0.1 s; the inbox read flags change in place)."""
    from . import digest
    return digest(repr(_news(engine)))


OFFER_KINDS = sorted({name for name, *_ in offers.CLASSES.values()})


def tables(engine):
    def injury_cov():
        u = C.cache(engine).get('injury_unsupported')
        return f'not read: {u}' if u else ''

    offer_view = (
        "SELECT o.idx, o.offer_type, o.person_idx, COALESCE(NULLIF(pe.{person.Pcna}, ''), "
        "TRIM(COALESCE(pe.{person.Pfna}, '') || ' ' || COALESCE(pe.{person.Psna}, ''))) AS person_name, "
        "o.team1_idx, t1.{team.Tlna|Tsna|dbnm} AS team1, o.team2_idx, t2.{team.Tlna|Tsna|dbnm} AS team2, "
        "o.state_code, o.amount_raw, "
        # roles of full transfers and loans, checked against the club transfer history screen
        "CASE WHEN o.offer_type IN ('full_transfer', 'loan') THEN o.team1_idx END AS buying_team_idx, "
        "CASE WHEN o.offer_type IN ('full_transfer', 'loan') THEN t1.{team.Tlna|Tsna|dbnm} END AS buying_team, "
        "CASE WHEN o.offer_type IN ('full_transfer', 'loan') THEN o.team3_idx END AS selling_team_idx, "
        "CASE WHEN o.offer_type IN ('full_transfer', 'loan') THEN t3.{team.Tlna|Tsna|dbnm} END AS selling_team "
        "FROM transfer_offer o LEFT JOIN person pe ON pe.idx = o.person_idx "
        "LEFT JOIN team t1 ON t1.idx = o.team1_idx LEFT JOIN team t2 ON t2.idx = o.team2_idx "
        "LEFT JOIN team t3 ON t3.idx = o.team3_idx")
    injury_view = (
        "SELECT pi.person_idx, COALESCE(NULLIF(pe.{person.Pcna}, ''), TRIM(COALESCE(pe.{person.Pfna}, '') || ' ' || "
        "COALESCE(pe.{person.Psna}, ''))) AS person_name, pi.injury_idx, inj.{injury.Inam|dbnm} AS injury, "
        "pi.started FROM player_injury pi LEFT JOIN person pe ON pe.idx = pi.person_idx "
        "LEFT JOIN injury inj ON inj.idx = pi.injury_idx")
    return [
        SourceTable('transfer_offer', 'every transfer, loan, trial, trade, draft, enquiry and B-club offer the '
                    'transfer manager holds (both offer vectors): offer type, player, teams, native state, amount',
                    [Column('container', 'TEXT', "'first_offer_vector' (+0x20) or 'second_offer_vector' (+0x38)"),
                     Column('slot', 'INTEGER', 'position in the vector'),
                     Column('object', 'TEXT', 'native object address (same object may sit in both vectors)'),
                     Column('offer_type', 'TEXT', 'offer class: ' + ', '.join(OFFER_KINDS)),
                     Column('person_idx', 'INTEGER', 'the player the offer is for', references='person'),
                     Column('team1_idx', 'INTEGER', 'team field +0x40: the buying team (full transfers) or the '
                            'borrowing team (loans); checked against the club transfer history screen',
                            references='team'),
                     Column('team1_club_idx', 'INTEGER', 'club of team1', references='club'),
                     Column('team2_idx', 'INTEGER', 'team field +0x48: equals team1 on most offers; on full '
                            'transfers into a youth side it is the buying club\'s team the player joins (the U21 '
                            'team for Newcastle youth signings); role inferred', references='team'),
                     Column('team2_club_idx', 'INTEGER', 'club of team2', references='club'),
                     Column('team3_idx', 'INTEGER', 'team field +0x50: the selling team (full transfers) or the '
                            'loaning, parent team (loans): 26 of 26 Newcastle transfers and loans that are both an '
                            'offer and a row of club_transfer_history have team1 = buyer and team3 = seller, none '
                            'swapped (13 Dec 2030); NULL when the seller is not a team (free agents)',
                            references='team'),
                     Column('team3_club_idx', 'INTEGER', 'club of team3', references='club'),
                     Column('state_code', 'INTEGER', 'native offer state byte +0x8D (labels not mapped)'),
                     Column('amount_raw', 'INTEGER', 'signed int32 +0x58: loans the monthly fee while playing (GBP); '
                            'full transfers: the fee (inferred: matches known Newcastle purchase fees)'),
                     *(Column(f'date_{o:x}', 'TEXT', f'packed date at +0x{o:X} (meaning not established; NULL when '
                              'not a date)') for o in (0x70, 0x74, 0x78, 0x7C)),
                     Column('loan_playing_weekly_wage', 'INTEGER', 'loans: weekly wage while playing (GBP, +0x108)'),
                     Column('loan_unused_weekly_wage', 'INTEGER', 'loans: weekly wage when not playing (+0x100)'),
                     Column('loan_unused_monthly_fee', 'INTEGER', 'loans: monthly fee when not playing (+0x104)')],
                    lambda: _offers(engine), cost_note='one bulk read',
                    mode='lazy', invalidation='content', fingerprint=lambda: _offer_fingerprint(engine),
                    source_note='BASE_TRANSFER_MANAGER offer vectors (live_transfer_offers checks)',
                    indexes=('person_idx', 'team1_club_idx'),
                    manager={'scope': 'own_club', 'own_club_columns': ['team1_club_idx', 'team2_club_idx',
                                                                       'team3_club_idx'],
                             'reason': 'the game shows the manager offers his club made or received; other clubs\' '
                                       'offers are not shown'},
                    views={'transfer_offer_view': offer_view}),
        SourceTable('player_injury', 'every current injury of every player: injury type and start date',
                    [Column('person_idx', 'INTEGER', 'injured player', references='person'),
                     Column('entry', 'INTEGER', 'position in the player\'s injury vector'),
                     Column('injury_idx', 'INTEGER', 'injury type definition', references='injury'),
                     Column('started', 'TEXT', 'stored start date (+0x20)'),
                     Column('object', 'TEXT', 'native injury instance address')],
                    lambda: _injuries(engine), cost_note='bulk reads over every player',
                    mode='lazy', invalidation='content', fingerprint=lambda: _injury_fingerprint(engine),
                    source_note='player primary +0xF0 injury vector (player_health.injury layout; slot 21 0xD09BB0 '
                                'checked per class)', indexes=('person_idx',), coverage=injury_cov,
                    manager={'scope': 'public', 'reason': 'current injuries are shown on any player\'s profile '
                                                          'and in news'},
                    views={'player_injury_view': injury_view}),
        SourceTable('news_item', 'every news item the game holds (all clubs and competitions) and every item of the '
                    'human manager\'s inbox: unique id, news class, date, read flag',
                    [Column('unique_id', 'INTEGER', 'news item unique id (+0x90)'),
                     Column('news_class', 'TEXT', 'native news class (RTTI), e.g. INJURY_INJURED_NEWS, '
                            'MATCH_REPORT_NEWS, CONTRACT_DECISION_NEWS'),
                     Column('date', 'TEXT', 'item date (+0x88)'),
                     Column('source', 'TEXT', "'news_manager' (NEWS_MANAGER +0xB8: every news item in the game) or "
                            "'inbox' (a human manager's own inbox copy, HUMAN +0x350; personal items are only here)"),
                     Column('inbox_owner_idx', 'INTEGER', 'inbox rows: the human manager', references='person'),
                     Column('read', 'INTEGER', 'flags bit 0 (read, as the inbox shows it)'),
                     Column('flags', 'INTEGER', 'u16 flags +0x98 (server key Nfla), other bits unmapped'),
                     Column('in_inbox', 'INTEGER', '1 when a human manager\'s inbox holds an item with this unique id')],
                    lambda: _news(engine), cost_note='one bulk read',
                    mode='lazy', invalidation='content', fingerprint=lambda: _news_fingerprint(engine),
                    source_note='NEWS_MANAGER +0xB8 and HUMAN +0x350 inbox (ui_recipes_news layout)',
                    indexes=('unique_id',),
                    manager={'scope': 'own_club', 'own_club_rule': "source = 'inbox'",
                             'reason': 'the manager sees his inbox; news for other clubs is not shown as stored here'}),
    ]


