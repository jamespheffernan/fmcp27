"""Stored compact VIRTUAL_PLAYER identity, without generated-profile lookup."""
import struct

from . import database, players, world


BINDING_KIND = 'stored_virtual_identity_v1'
PERSON_RVA = 0x55CB9F8
COMPACT_BYTES = 64


def verify_native(read, base):
    """Pin the accepted identity, PERSON serializer, team-index and cache-sign routes."""
    for rva, expected in NATIVE_SPANS:
        if read(base + rva, len(expected)) != expected:
            raise ValueError(f'Compact virtual identity native layout changed at RVA {rva:#x}')


def inspect(read, address, tables) -> dict:
    """Return checked identity fields and private `_raw` bytes for source rechecks.

    The caller owns the save/roster binding and verifies its consumed ReadSet.
    Cache index is availability metadata and never enters the identity tuple.
    """
    if type(address) is not int or address < 4096 or address % 8:
        raise ValueError('Invalid compact virtual player address')
    if (not isinstance(tables, tuple) or len(tables) != 3
            or any(type(value) is not int for value in tables)):
        raise ValueError('Invalid compact virtual player layout')
    base = tables[0] - players.RVA[0]
    if tables != tuple(base + rva for rva in players.RVA):
        raise ValueError('Compact virtual player layout changed')
    verify_native(read, base)
    world.typed(read, base, address, 'virtual_player')
    raw = read(address, COMPACT_BYTES)
    if (len(raw) != COMPACT_BYTES
            or players.u64(raw) != base + world.TYPES['virtual_player'][0]
            or players.u64(raw, 0x20) != base + PERSON_RVA):
        raise ValueError('Compact virtual player or embedded PERSON type changed')
    displacement, info = struct.unpack('<qQ', read(base + PERSON_RVA - 16, 16))
    if displacement != -0x20:
        raise ValueError('Compact virtual PERSON displacement changed')
    if info < 4096 or info % 8:
        raise ValueError('Invalid compact virtual PERSON type information')
    name = players.u64(read(info + 8, 8))
    if name < 4096:
        raise ValueError('Invalid compact virtual PERSON RTTI name pointer')
    expected_name = b'N2db14VIRTUAL_PLAYERE\0'
    if read(name, len(expected_name)) != expected_name:
        raise ValueError('Compact virtual PERSON RTTI changed')
    if (players.u64(read(base + PERSON_RVA + 2*8, 8)) != base + 0x1475750
            or players.u64(read(base + world.TYPES['virtual_player'][0] + 29*8, 8)) != base + 0x18A4A9C):
        raise ValueError('Compact virtual identity or team getter changed')

    index, primary, secondary = struct.unpack_from('<III', raw, 0x28)
    if not primary:
        raise ValueError('Compact virtual primary identity is missing')
    people = database.table(read, base, 'people')
    if (index >= people['count']
            or world.pointer(read, people['start'] + index*8) != address + 0x20):
        raise ValueError('Compact virtual player is no longer at its canonical PERSON index')
    if read(address, COMPACT_BYTES) != raw:
        raise ValueError('Compact virtual player changed during identity inspection')
    return {
        'identity': (BINDING_KIND, index, primary, secondary),
        'native_identity': {'database_index': index, 'native_id': primary,
                            'random_id': None if secondary == primary else secondary},
        'stored_team_index': struct.unpack_from('<i', raw, 8)[0],
        'cache_index': struct.unpack_from('<h', raw, 0x14)[0],
        '_raw': raw,
    }


